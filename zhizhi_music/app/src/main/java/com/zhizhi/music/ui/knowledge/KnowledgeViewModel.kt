    init {
        filterByCategory("入门刚需")
    }

    fun filterByCategory(category: String) {
        _selectedCategory.value = category
        _items.value = allItems.filter { it.category == category }
    }

    fun search(query: String) {
        _items.value = if (query.isEmpty()) {
            allItems.filter { it.category == _selectedCategory.value }
        } else {
            allItems.filter { it.title.contains(query) || it.content.contains(query) }
        }
    }
